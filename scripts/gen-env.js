// Writes .env.example and the variable table in README.md from server/config.js,
// so the list of settings has one source of truth.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VARIABLES } from '../server/config.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

let env = '# Hoodey settings. Copy to .env for local runs; on Railway add these under Variables.\n# Generated by `npm run env:example` from server/config.js. Empty values use the default.\n';
let group = '';
for (const v of VARIABLES) {
  if (v.group !== group) { group = v.group; env += `\n# ── ${group} ${'─'.repeat(Math.max(3, 60 - group.length))}\n`; }
  const opts = v.options ? ` (${v.options.join(' | ')})` : '';
  env += `# ${v.desc}${opts}${v.secret ? ' [SECRET]' : ''}\n`;
  if (v.name === 'PORT') { env += `# ${v.name}=${v.default}\n`; continue; } // never override Railway's own PORT
  const val = v.secret ? '' : String(v.default);
  env += `${v.name}=${val.includes(' ') ? JSON.stringify(val) : val}\n`;
}
fs.writeFileSync(path.join(root, '.env.example'), env);

const cell = (s) => String(s).replace(/\|/g, '\\|');
let table = '| Variable | Default | What it does |\n|---|---|---|\n';
group = '';
for (const v of VARIABLES) {
  if (v.group !== group) { group = v.group; table += `| **${group}** | | |\n`; }
  const def = v.default === '' ? '_empty_' : `\`${cell(v.default)}\``;
  table += `| \`${v.name}\`${v.secret ? ' 🔒' : ''} | ${def} | ${cell(v.desc)}${v.options ? ` Options: ${v.options.map((o) => '`' + o + '`').join(', ')}.` : ''} |\n`;
}
const readmePath = path.join(root, 'README.md');
if (fs.existsSync(readmePath)) {
  const readme = fs.readFileSync(readmePath, 'utf8');
  const next = readme.replace(/<!-- ENV:START -->[\s\S]*<!-- ENV:END -->/, `<!-- ENV:START -->\n${table}<!-- ENV:END -->`);
  fs.writeFileSync(readmePath, next);
}
console.log(`Wrote .env.example and README table (${VARIABLES.length} variables).`);
